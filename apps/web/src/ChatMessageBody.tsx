import Markdown, { type Components, type ExtraProps } from "react-markdown";
import { createContext, memo, useContext, type ComponentProps, type ReactNode } from "react";
import type { PluggableList } from "unified";
import { dialogueHighlight } from "./dialogueHighlight";
import { privateMarkdownSlots } from "./privateMarkdown";

type MaskSlots = { prefix: string; count: number; render: (index: number) => ReactNode };
const MaskContext = createContext<MaskSlots | undefined>(undefined);

function MessageSpan({ node, children, ...props }: ComponentProps<"span"> & ExtraProps) {
  const masks = useContext(MaskContext);
  const index = node?.properties["data-private-slot"];
  if (masks && typeof index === "number" && index >= 0 && index < masks.count) return <span {...props}>{masks.render(index)}</span>;
  return <span {...props}>{children}</span>;
}

// React uses component identity to preserve reveal state. These renderers must
// stay outside ChatMessageBody; conversation polling re-renders its parent.
const messageComponents: Components = {
  span: MessageSpan,
  a({ href, children }) {
    // Keep app-local URLs and unsafe schemes out of model-authored navigation.
    if (!href || !/^https?:\/\//i.test(href)) return <span>{children}</span>;
    return <a href={href} target="_blank" rel="noopener noreferrer">{children}</a>;
  },
  img({ alt }) {
    // Rendering an external image would issue a request without the user's action.
    return <span className="message-image-placeholder">[图片链接已隐藏{alt ? `：${alt.slice(0, 120)}` : ""}]</span>;
  },
};

const inlineComponents: Components = {
  ...messageComponents,
  p: ({ children }) => <span>{children}</span>,
  h1: ({ children }) => <strong>{children}</strong>,
  h2: ({ children }) => <strong>{children}</strong>,
  h3: ({ children }) => <strong>{children}</strong>,
  h4: ({ children }) => <strong>{children}</strong>,
  h5: ({ children }) => <strong>{children}</strong>,
  h6: ({ children }) => <strong>{children}</strong>,
  blockquote: ({ children }) => <span>{children}</span>,
  ul: ({ children }) => <span>{children}</span>,
  ol: ({ children }) => <span>{children}</span>,
  li: ({ children }) => <span>{children}</span>,
  pre: ({ children }) => <span>{children}</span>,
  hr: () => <span> — </span>,
};

/** Chat text is untrusted, whether written by a player or generated by a model. */
export const ChatMessageBody = memo(function ChatMessageBody({ text, character = false, inline = false, masks }: {
  text: string; character?: boolean; inline?: boolean;
  masks?: MaskSlots;
}) {
  const Wrapper = inline ? "span" : "div";
  const plugins: PluggableList = [];
  if (masks) plugins.push([privateMarkdownSlots, { prefix: masks.prefix, count: masks.count }]);
  if (character) plugins.push(dialogueHighlight);
  return <MaskContext value={masks}><Wrapper className={`message-content${inline ? " message-content-inline" : ""}`}>
    <Markdown rehypePlugins={plugins} components={inline ? inlineComponents : messageComponents}>{text}</Markdown>
  </Wrapper></MaskContext>;
});
